_gen_keypair(){
  # prints: priv\npub
  local priv pub
  priv="$(wg genkey 2>/dev/null | tr -d '\r\n' || true)"
  [[ -n "$priv" ]] || return 1
  pub="$(printf '%s' "$priv" | wg pubkey 2>/dev/null | tr -d '\r\n' || true)"
  [[ -n "$pub" ]] || return 1
  printf '%s\n%s\n' "$priv" "$pub"
}

_build_remote_mimic_blocks(){
  local blocks="" n
  while read -r n; do
    n="$(safe_name "$n")"; [[ -n "$n" ]] || continue
    mimic_should_include_profile_for_remote "$n" || continue
    blocks+="$(mimic_profile_block_remote "$n" 2>/dev/null || true)"
  done < <(profiles_list)
  printf '%s' "$blocks"
}

_build_remote_wg_conf(){
  # uses: OUT_PRIVKEY IR_PUBKEY, addr/allowed
  local addr="" allowed=""

  if [[ "${ENABLE_TUN_IPV4:-1}" == "1" && -n "${OUT_WG_IP:-}" && -n "${TUN_SUBNET:-}" ]]; then
    local prefix4="${TUN_SUBNET##*/}"
    addr="${OUT_WG_IP}/${prefix4}"
    allowed="${IR_WG_IP}/32"
  fi

  if [[ "${ENABLE_TUN_IPV6:-0}" == "1" && -n "${TUN_SUBNET6:-}" && -n "${OUT_WG_IP6:-}" && -n "${IR_WG_IP6:-}" ]]; then
    local prefix6="${TUN_SUBNET6##*/}"
    [[ -n "$addr" ]] && addr+=", "
    addr+="${OUT_WG_IP6}/${prefix6}"
    [[ -n "$allowed" ]] && allowed+=", "
    allowed+="${IR_WG_IP6}/128"
  fi

  [[ -n "$addr" && -n "$allowed" ]] || die "No tunnel address families enabled. Enable IPv4 and/or IPv6."

  cat <<CFG
# Generated by AZHDAR v${SCRIPT_VERSION} - WireGuard (OUT) offline bundle
[Interface]
PrivateKey = ${OUT_PRIVKEY}
Address = ${addr}
ListenPort = ${WG_PORT}
MTU = ${MTU}

[Peer]
PublicKey = ${IR_PUBKEY}
CFG

  if [[ "${USE_PSK}" == "1" && -n "${PSK_VALUE:-}" ]]; then
    echo "PresharedKey = ${PSK_VALUE}"
  fi

  cat <<CFG
AllowedIPs = ${allowed}
CFG
}

