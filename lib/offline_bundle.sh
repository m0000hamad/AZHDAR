detect_if(){
  local ifc=""
  ifc="$(ip -4 route get 1.1.1.1 2>/dev/null | awk '{for(i=1;i<=NF;i++) if($i=="dev"){print $(i+1); exit}}' || true)"
  [[ -n "${ifc}" ]] || ifc="$(ip -4 route show default 2>/dev/null | awk 'NR==1{print $5; exit}' || true)"
  [[ -n "${ifc}" ]] || ifc="$(ip -br link 2>/dev/null | awk '$1!="lo" && $2 ~ /UP/ {print $1; exit}' || true)"
  echo "${ifc}"
}

pkg_mgr(){
  command -v apt-get >/dev/null 2>&1 && { echo apt; return; }
  command -v dnf >/dev/null 2>&1 && { echo dnf; return; }
  command -v yum >/dev/null 2>&1 && { echo yum; return; }
  command -v pacman >/dev/null 2>&1 && { echo pacman; return; }
  echo unknown
}

os_codename(){
  local codename=""
  if [[ -r /etc/os-release ]]; then
    # shellcheck disable=SC1091
    . /etc/os-release 2>/dev/null || true
    codename="${VERSION_CODENAME:-${UBUNTU_CODENAME:-}}"
    if [[ -z "${codename}" && -n "${VERSION:-}" ]]; then
      local tmp
      tmp="${VERSION#*(}"; tmp="${tmp%%)*}"
      if [[ -n "${tmp}" && "${tmp}" != "${VERSION}" ]]; then
        codename="${tmp%% *}"
      fi
    fi
  fi
  if [[ -z "${codename}" ]] && command -v lsb_release >/dev/null 2>&1; then
    codename="$(lsb_release -cs 2>/dev/null || true)"
  fi
  echo "${codename,,}"
}

apt_install_retry(){
  export DEBIAN_FRONTEND=noninteractive
  apt-get install -y "$@" >/dev/null 2>&1 && return 0
  apt-get -f install -y >/dev/null 2>&1 || true
  apt-get install -y "$@" >/dev/null 2>&1
}

install_deps(){
  local pm; pm="$(pkg_mgr)"
  case "$pm" in
    apt)
      export DEBIAN_FRONTEND=noninteractive
      apt-get update -y >/dev/null 2>&1 || true

      # IMPORTANT: Mimic-DKMS requires these.
      if ! apt-get install -y dkms build-essential "linux-headers-$(uname -r)" >/dev/null 2>&1; then
        apt-get -f install -y >/dev/null 2>&1 || true
        apt-get install -y dkms build-essential "linux-headers-$(uname -r)" >/dev/null 2>&1 ||           apt-get install -y dkms build-essential linux-headers-generic >/dev/null 2>&1 || true
      fi

      # Core networking tools
      apt_install_retry wireguard-tools wireguard iptables iproute2 iputils-ping curl ca-certificates git netcat-openbsd tcpdump python3 xz-utils lz4 >/dev/null 2>&1 || true
      ;;
    dnf)
      dnf install -y wireguard-tools iptables iproute iputils curl ca-certificates git make gcc dkms nmap-ncat tcpdump python3 xz lz4 >/dev/null 2>&1 || true
      ;;
    yum)
      yum install -y wireguard-tools iptables iproute iputils curl ca-certificates git make gcc dkms nmap-ncat tcpdump python3 xz lz4 >/dev/null 2>&1 || true
      ;;
    pacman)
      pacman -Sy --noconfirm wireguard-tools iptables iproute2 iputils curl ca-certificates git base-devel dkms netcat tcpdump python xz lz4 >/dev/null 2>&1 || true
      ;;
    *)
      echo "Unsupported package manager. Please install: wireguard-tools, iptables, iproute2, curl, ca-certificates, dkms" >&2
      ;;
  esac
  modprobe wireguard >/dev/null 2>&1 || true
}

install_mimic_apt_only(){
  # Mimic installer (Debian/Ubuntu). On other distros we skip (best-effort).
  if command -v mimic >/dev/null 2>&1; then
    return 0
  fi
  if ! command -v apt-get >/dev/null 2>&1; then
    echo "[!] mimic not installed (no apt). Skipping mimic install." >&2
    return 0
  fi

  local codename; codename="$(os_codename)"
  if [[ -z "${codename}" ]]; then
    echo "[!] Cannot detect OS codename; skipping mimic install." >&2
    return 0
  fi

  local json urls deb1 deb2 tmp
  tmp="/tmp/mimic-install.$$"
  rm -rf "$tmp"; mkdir -p "$tmp"

  json="$(curl -fsSL --max-time 10 https://api.github.com/repos/hack3ric/mimic/releases/latest 2>/dev/null || true)"
  urls="$(printf "%s" "$json" | sed -n 's/.*"browser_download_url"[ ]*:[ ]*"\([^"]*\)".*//p' || true)"

  deb1="$(printf "%s
" "$urls" | grep -E "/${codename}_mimic_[^/]*_amd64\.deb$" | head -n1 || true)"
  deb2="$(printf "%s
" "$urls" | grep -E "/${codename}_mimic-dkms_[^/]*_amd64\.deb$" | head -n1 || true)"

  # Mirror fallback (useful when GitHub is blocked). You can override:
  #   export AZHDAR_MIRROR_BASE="https://api.github.com/repos/m0000hamad/AZHDAR/contents/assets"
  local MIRROR_BASE="${AZHDAR_MIRROR_BASE:-${ASSET_MIRROR_BASE:-https://api.github.com/repos/m0000hamad/AZHDAR/contents/assets}}"
  if [[ -z "$deb1" || -z "$deb2" ]]; then
    deb1="${MIRROR_BASE}/${codename}_mimic_0.7.0-1_amd64.deb"
    deb2="${MIRROR_BASE}/${codename}_mimic-dkms_0.7.0-1_amd64.deb"
  fi

  azhdar_gh_hdr_args "$deb1" 2>/dev/null || AZ_GH_HDR=()
  curl -fL --connect-timeout 6 --max-time 120 ${AZ_GH_HDR[@]+"${AZ_GH_HDR[@]}"} "$deb1" -o "$tmp/mimic.deb" >/dev/null 2>&1 || true
  azhdar_gh_hdr_args "$deb2" 2>/dev/null || AZ_GH_HDR=()
  curl -fL --connect-timeout 6 --max-time 120 ${AZ_GH_HDR[@]+"${AZ_GH_HDR[@]}"} "$deb2" -o "$tmp/mimic-dkms.deb" >/dev/null 2>&1 || true

  if [[ -s "$tmp/mimic.deb" && -s "$tmp/mimic-dkms.deb" ]]; then
    dpkg-deb -I "$tmp/mimic.deb" >/dev/null 2>&1 || return 0
    dpkg-deb -I "$tmp/mimic-dkms.deb" >/dev/null 2>&1 || return 0

    if ! apt-get install -y "$tmp/mimic.deb" "$tmp/mimic-dkms.deb" >/dev/null 2>&1; then
      apt-get -f install -y >/dev/null 2>&1 || true
      apt-get install -y "$tmp/mimic.deb" "$tmp/mimic-dkms.deb" >/dev/null 2>&1 || true
    fi
  fi
}

detect_src_ip(){
  # args: dst_ip
  local dst="$1" src=""
  src="$(ip -4 route get "$dst" 2>/dev/null | awk '/src/ {for(i=1;i<=NF;i++){if($i=="src"){print $(i+1); exit}}}' || true)"
  echo "$src"
}

open_ports_and_rst_drop(){
  local port="__WG_PORT__"
  # Allow BOTH TCP+UDP on the public port (WG is UDP, Mimic makes it look TCP)
  local proto
  for proto in tcp udp; do
    iptables -C INPUT -p "$proto" --dport "$port" -j ACCEPT >/dev/null 2>&1 || iptables -I INPUT -p "$proto" --dport "$port" -j ACCEPT >/dev/null 2>&1 || true
  done
  if command -v ufw >/dev/null 2>&1; then
    ufw allow "${port}/tcp" >/dev/null 2>&1 || true
    ufw allow "${port}/udp" >/dev/null 2>&1 || true
  fi
  # Prevent kernel from sending RST on Mimic fake TCP flow
  iptables -t raw -C OUTPUT -p tcp --sport "$port" --tcp-flags RST RST -j DROP >/dev/null 2>&1 ||     iptables -t raw -I OUTPUT -p tcp --sport "$port" --tcp-flags RST RST -j DROP >/dev/null 2>&1 || true
}

apply_files(){
  local wan_if="$1"

  mkdir -p /etc/wireguard /etc/mimic

  # WireGuard key + conf
  cat >"/etc/wireguard/__WG_IF__.key" <<'K'
__OUT_PRIVKEY__
K
  chmod 600 "/etc/wireguard/__WG_IF__.key" || true

  cat >"/etc/wireguard/__WG_IF__.conf" <<'WG'
__WG_CONF__
WG
  chmod 600 "/etc/wireguard/__WG_IF__.conf" || true

  # Mimic conf (OUT) - compute local src IP automatically
  local src_ip
  src_ip="$(detect_src_ip "__IR_PUBLIC_IP__")"
  if [[ -z "$src_ip" ]]; then
    # fallback: first IPv4 on wan_if
    src_ip="$(ip -4 addr show dev "$wan_if" 2>/dev/null | awk '/inet /{print $2}' | head -n1 | cut -d/ -f1 || true)"
  fi

  cat >"/etc/mimic/${wan_if}.conf" <<EOF
# Generated by AZHDAR v__SCRIPT_VERSION__ - Mimic config (OUT)
log.verbosity = info
handshake = 0:0

# Profile: __PROFILE__
filter = local=${src_ip}:__WG_PORT__
filter = remote=__IR_PUBLIC_IP__:__WG_PORT__
EOF
  chmod 644 "/etc/mimic/${wan_if}.conf" || true
}

enable_services(){
  local wan_if="$1"
  systemctl daemon-reload >/dev/null 2>&1 || true
  systemctl enable --now "wg-quick@__WG_IF__" >/dev/null 2>&1 || true
  systemctl enable --now "mimic@${wan_if}" >/dev/null 2>&1 || true
}

parse_peer_ips(){
  # Best-effort: parse AllowedIPs from WireGuard conf (first peer).
  local conf="/etc/wireguard/__WG_IF__.conf"
  [[ -r "$conf" ]] || return 0
  sed -n 's/^AllowedIPs[[:space:]]*=[[:space:]]*//p' "$conf" | head -n1 | \
    tr ',' '\n' | awk '{print $1}' | cut -d/ -f1 | sed '/^$/d'
}

wg_handshake_recent(){
  local ifc="__WG_IF__" hs now
  command -v wg >/dev/null 2>&1 || return 1
  hs="$(wg show "$ifc" latest-handshakes 2>/dev/null | awk 'NR==1{print $2}' || echo 0)"
  [[ "$hs" =~ ^[0-9]+$ ]] || return 1
  (( hs > 0 )) || return 1
  now="$(date +%s 2>/dev/null || echo 0)"
  (( now - hs <= 180 ))
}

wg_ping_peer_once(){
  # args: ip
  local ifc="__WG_IF__" ip="$1"
  [[ -n "$ip" ]] || return 1
  if [[ "$ip" == *:* ]]; then
    ping -6 -c 1 -W 1 -I "$ifc" "$ip" >/dev/null 2>&1
  else
    ping -4 -c 1 -W 1 -I "$ifc" "$ip" >/dev/null 2>&1
  fi
}

final_link_check(){
  # Goal: at the end on OUT, print OK if OUT<->IR link is established.
  local ok=0 try ip

  # Wait a bit for handshake (IR keepalive will usually trigger this).
  for try in $(seq 1 15); do
    wg_handshake_recent && { ok=1; break; }
    sleep 2
  done

  # If no recent handshake yet, attempt ping to peer WG IP(s) (best-effort).
  if (( ok == 0 )); then
    while read -r ip; do
      wg_ping_peer_once "$ip" && { ok=1; break; }
    done < <(parse_peer_ips || true)
  fi

  if (( ok == 1 )); then
    echo "OK"
    return 0
  fi

  echo "NOT OK"
  echo "Debug: wg show __WG_IF__" >&2
  return 1
}

main(){
  need_root

  local wan_if
  wan_if="$(detect_if)"
  if [[ -z "${wan_if}" ]]; then
    echo "Cannot detect WAN interface." >&2
    exit 7
  fi

  echo "[*] WAN interface: ${wan_if}"
  echo "[*] Installing deps (best-effort)..."
  install_deps

  echo "[*] Installing mimic (best-effort, apt only)..."
  install_mimic_apt_only

  echo "[*] Opening ports + applying RST-drop (best-effort)..."
  open_ports_and_rst_drop || true

  echo "[*] Writing configs..."
  apply_files "$wan_if"

  echo "[*] Enabling services..."
  enable_services "$wan_if"

  echo "[+] Done. Check on OUT:" 
  echo "    systemctl status wg-quick@__WG_IF__ --no-pager"
  echo "    systemctl status mimic@${wan_if} --no-pager"
  echo "    wg show __WG_IF__"

  echo "[*] Link check (OUT -> IR):"
  final_link_check || true
}

