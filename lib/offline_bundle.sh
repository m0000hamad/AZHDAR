_make_self_extract(){
  # args: sourcedir outfile
  local src="$1" out="$2"
  local tgz="${out}.tar.gz"
  tar -C "$(dirname "$src")" -czf "$tgz" "$(basename "$src")"

  local b64
  b64="$(base64 -w0 "$tgz" 2>/dev/null || base64 "$tgz" 2>/dev/null | tr -d '\n')"

  cat >"$out" <<'EOSEL'
#!/usr/bin/env bash
set -Eeuo pipefail
umask 077

_payload_b64='__PAYLOAD_B64__'
_tmp="/tmp/azhdar-offline-$$"
mkdir -p "$_tmp"

cleanup(){ rm -rf "$_tmp" >/dev/null 2>&1 || true; }
trap cleanup EXIT

printf '%s' "$_payload_b64" | base64 -d >"$_tmp/bundle.tgz"

tar -C "$_tmp" -xzf "$_tmp/bundle.tgz"

cd "$_tmp/__DIR__"
exec bash ./run-remote.sh
EOSEL

  python3 - <<PY
import pathlib
p = pathlib.Path("$out")
text = p.read_text()
text = text.replace("__PAYLOAD_B64__", "${b64}")
text = text.replace("__DIR__", "$(basename "$src")")
p.write_text(text)
PY

  chmod +x "$out" || true
  rm -f "$tgz" >/dev/null 2>&1 || true
}

advanced_tunnel_ip_wizard(){
  # Offline-friendly tunnel IP allocator (no SSH required).
  echo
  echo -e "${DIM}Tunnel IP allocation:${RST}"
  echo " 1) Auto (pick subnet + WG IPs)"
  echo " 2) Manual (set subnet + WG IPs)"
  local _def="1" _ia=""
  [[ "${TUN_IP_ASSIGN:-auto}" == "manual" ]] && _def="2" || true
  while true; do
    read -rp "Select [${_def}]: " _ia || true
    _ia="${_ia:-${_def}}"
    case "${_ia}" in
      1) TUN_IP_ASSIGN="auto"; break ;;
      2) TUN_IP_ASSIGN="manual"; break ;;
      *) warn "Invalid choice." ;;
    esac
  done

  if [[ "${TUN_IP_ASSIGN}" == "manual" ]]; then
    # Provided by lib/advanced_tunnel_ip.sh (loaded by azhdar)
    tunnel_manual_set || true
  else
    if [[ "${ENABLE_TUN_IPV4:-1}" == "1" ]]; then
      pick_subnet_pairwise || true
    fi
    if [[ "${ENABLE_TUN_IPV6:-0}" == "1" ]]; then
      pick_subnet6_pairwise || true
    fi
  fi
}
offline_bundle_wizard(){
  banner
  echo -e "${BOLD}${WHT}Offline install (no SSH) - build remote one-liner bundle${RST}"
  hr
  [[ -n "${PROFILE:-}" ]] || die "No active profile. Create/select one first."

  install_deps_local

  # Local IR public IP suggestion
  local myip=""
  myip="$(public_ipv4 2>/dev/null || true)"
  [[ -n "$myip" ]] && IR_PUBLIC_IP="${IR_PUBLIC_IP:-$myip}"
  IR_PUBLIC_IP="$(prompt_ipv4 "IR public IP (this server)" "${IR_PUBLIC_IP:-}")"

  OUT_PUBLIC_IP="$(prompt_host "OUT public IP/host (no SSH)" "${OUT_PUBLIC_IP:-}")"

  # Mimic filter IP on IR: src IP used to reach OUT
  if [[ -z "${IR_LOCAL_IP:-}" && -n "${OUT_PUBLIC_IP:-}" ]]; then
    IR_LOCAL_IP="$(detect_src_ip "${OUT_PUBLIC_IP}" 2>/dev/null | tr -d '\n\r' || true)"
  fi
  if [[ -z "${IR_LOCAL_IP:-}" ]]; then
    IR_LOCAL_IP="$(prompt_ipv4 'IR local/source IP used to reach OUT (Mimic filter)' '')"
  else
    info "IR local IP (auto): ${IR_LOCAL_IP}"
  fi

  # Port selection: only local checks + profile conflicts
  local suggested
  suggested="$(suggest_wg_port || true)"
  [[ -n "$suggested" ]] && WG_PORT="$suggested"
  while true; do
    WG_PORT="$(prompt_port "Tunnel public port (looks like TCP)" "${WG_PORT:-443}")"

    if ! ports_validate_current_or_warn; then
      local _sug
      _sug="$(ports_suggest_free_near tcp "${WG_PORT}" || true)"
      if [[ -n "${_sug:-}" && "${_sug}" != "${WG_PORT}" ]]; then
        warn "Suggested free port near ${WG_PORT}: ${_sug}"
        if [[ "$(prompt_yesno "Use suggested port ${_sug}?" "Y")" == "Y" ]]; then
          WG_PORT="${_sug}"
          continue
        fi
      fi
      warn "Selected tunnel/forward port conflicts with another profile. Check the warning above and choose a different port."
      continue
    fi

    local_port_in_use "${WG_PORT}" && warn "Selected WG_PORT=${WG_PORT} is in use on IR (this server)." || true
    break
  done

  # Optional forwarding (IR)
  echo
  echo -e "${BOLD}${WHT}Optional reverse-forward${RST}"
  hr
  echo -e "${DIM}This can forward public IR ports to OUT over the WG tunnel.${RST}"
  if [[ "$(prompt_yesno "Enable reverse-forward rules on IR?" "Y")" == "Y" ]]; then
    while true; do
      read -rp "Public TCP port(s) on IR to forward (comma-separated, empty=none) [${FORWARD_TCP_PORTS}]: " FORWARD_TCP_PORTS || true
      FORWARD_TCP_PORTS="${FORWARD_TCP_PORTS:-}"
      protect_ir_ssh_port || true
      read -rp "Public UDP port(s) on IR to forward (comma-separated, empty=none) [${FORWARD_UDP_PORTS}]: " FORWARD_UDP_PORTS || true
      FORWARD_UDP_PORTS="${FORWARD_UDP_PORTS:-}"
      VLESS_DST_PORT="$(prompt_port "Destination port on OUT (service bind port)" "${VLESS_DST_PORT:-2086}")"

      ports_validate_current_or_warn && break
      warn "One of the forward ports conflicts with another profile. Please re-enter only the forwarding ports, or leave them empty to disable forwarding."
    done
  else
    FORWARD_TCP_PORTS=""
    FORWARD_UDP_PORTS=""
  fi

  # Tunnel parameters (simplified)
  echo
  echo -e "${BOLD}${WHT}Tunnel parameters${RST}"
  hr
  echo -e "${DIM}MTU mode:${RST}"
  echo " 1) Auto (discover best common MTU)"
  echo " 2) Manual"
  local _mtu_mode_def="1" _mtu_mode=""
  [[ "${MTU_MODE:-manual}" == "manual" ]] && _mtu_mode_def="2" || true
  while true; do
    read -rp "Select [${_mtu_mode_def}]: " _mtu_mode || true
    _mtu_mode="${_mtu_mode:-${_mtu_mode_def}}"
    case "${_mtu_mode}" in
      1) MTU_MODE="auto"; break ;;
      2) MTU_MODE="manual"; break ;;
      *) warn "Invalid choice." ;;
    esac
  done
  if [[ "${MTU_MODE}" == "manual" ]]; then
    MTU="$(prompt_mtu "MTU" "${MTU:-1272}")"
  else
    MTU="${MTU:-1272}"
  fi
  KEEPALIVE="$(prompt_keepalive "PersistentKeepalive" "${KEEPALIVE:-25}")"

  echo -e "${DIM}Tunnel IP mode:${RST}"
  echo " 1) IPv4 only"
  echo " 2) IPv6 only"
  echo " 3) IPv4 + IPv6 (dual stack)"
  local _def_mode="1" _mode=""
  if [[ "${ENABLE_TUN_IPV4:-1}" == "1" && "${ENABLE_TUN_IPV6:-0}" != "1" ]]; then _def_mode="1"; fi
  if [[ "${ENABLE_TUN_IPV4:-1}" != "1" && "${ENABLE_TUN_IPV6:-0}" == "1" ]]; then _def_mode="2"; fi
  if [[ "${ENABLE_TUN_IPV4:-1}" == "1" && "${ENABLE_TUN_IPV6:-0}" == "1" ]]; then _def_mode="3"; fi
  while true; do
    read -rp "Select [${_def_mode}]: " _mode || true
    _mode="${_mode:-${_def_mode}}"
    case "${_mode}" in
      1) ENABLE_TUN_IPV4="1"; ENABLE_TUN_IPV6="0"; break ;;
      2) ENABLE_TUN_IPV4="0"; ENABLE_TUN_IPV6="1"; break ;;
      3) ENABLE_TUN_IPV4="1"; ENABLE_TUN_IPV6="1"; break ;;
      *) warn "Invalid." ;;
    esac
  done

  # Tunnel IP assignment (advanced helper)
  advanced_tunnel_ip_wizard || true

  echo
  echo -e "${BOLD}${WHT}WireGuard PSK${RST}"
  hr
  if [[ "$(prompt_yesno "Use PSK for WireGuard?" "Y")" == "Y" ]]; then
    USE_PSK="1"
  else
    USE_PSK="0"
  fi
  ensure_psk

  # Local key
  ensure_privkey_local
  IR_PUBKEY="$(get_pubkey_local | tr -d '\r' | tail -n1 || true)"
  [[ -n "${IR_PUBKEY:-}" ]] || die "Local WireGuard public key missing."

  # Remote keypair (generated locally)
  local kp priv pub
  kp="$(_gen_keypair)" || die "Failed to generate OUT WireGuard keypair."
  priv="$(printf '%s' "$kp" | sed -n '1p')"
  pub="$(printf '%s' "$kp" | sed -n '2p')"
  OUT_PRIVKEY="$priv"
  OUT_PUBKEY="$pub"

  info "IR pubkey : ${IR_PUBKEY}"
  info "OUT pubkey: ${OUT_PUBKEY} (generated locally for offline bundle)"

  # Save profile now (so keys remain cached)
  profile_save >/dev/null 2>&1 || true

  # Install mimic locally + write configs locally
  install_mimic_local
  write_mimic_conf_local

  # Write local WG config
  write_wg_conf_local

  # Apply forwarding locally (optional)
  azhdar_firewall_safety_local || true
  remove_forwarding_local || true
  setup_forward_ir || true
  persist_iptables_local || true

  # Start local services
  # Ensure local firewall allows WG_PORT (both TCP+UDP) + drop RST for fake TCP
  allow_mimic_port_local || true
  setup_rst_drop_local || true

  start_services_local || true

  # Build remote bundle
  step "Build remote offline bundle"
  local tmpdir bundle_dir outbase
  tmpdir="/tmp/azhdar-offline-bundle.${PROFILE}.$$"
  rm -rf "$tmpdir" >/dev/null 2>&1 || true
  mkdir -p "$tmpdir"

  bundle_dir="${tmpdir}/azhdar-remote-${PROFILE}"
  _build_remote_installer "$bundle_dir"

  outbase="${AZHDAR_HOME}/azhdar-remote-${PROFILE}-${SCRIPT_VERSION}.run"
  _make_self_extract "$bundle_dir" "$outbase"

  ok "Offline bundle created: ${outbase}"
  echo
  echo -e "${BOLD}${WHT}Remote one-liner${RST}"
  hr
  echo "1) Copy this file to OUT server (FTP/SCP/USB):"
  echo "   ${outbase}"
  echo
  echo "2) On OUT server run (one line):"
  echo "   sudo bash ./$(basename "$outbase")"
  echo
  echo -e "${DIM}Tip:${RST} After running, check: systemctl status wg-quick@${WG_IF} mimic@<wan_if>"
  echo
  pause
}
